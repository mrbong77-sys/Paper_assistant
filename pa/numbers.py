"""The numbers ledger: every number the manuscript states, with the file it comes from.

``05_data/numbers.csv`` has the columns ``key,value,unit,source,note``. ``source`` names the result file (and the key
or row inside it) or the command that produced the value, so a reviewer can trace every number (rule EV-01).

- ``pa numbers macros``  writes ``07_manuscript/numbers.tex`` with one ``\\newcommand{\\NumKey}{value}`` per row,
  so a LaTeX manuscript never retypes a result.
- ``pa numbers fill``    replaces ``{{num:key}}`` in a Markdown manuscript (used by ``pa build``).
- ``pa numbers audit``   lists numbers typed in the manuscript that the ledger does not hold, and ledger keys the
  manuscript never uses.
"""
from __future__ import annotations

import csv
import re
from dataclasses import dataclass
from pathlib import Path

FIELDS = ("key", "value", "unit", "source", "note")
KEY_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
PLACE = re.compile(r"\{\{\s*num:([A-Za-z][A-Za-z0-9_]*)\s*\}\}")
# numbers worth tracing: decimals, percentages, numbers with thousands separators, numbers >= 10
NUM = re.compile(r"(?<![\w.\-])(\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+\.\d+|\d{2,})(\s?%)?(?![\w])")
SKIP_CONTEXT = re.compile(r"(Table|Figure|Fig\.|Section|§|Eq\.|Appendix|ref|doi|arXiv|ISBN|ISSN|pp?\.)\s*$", re.I)


@dataclass
class Row:
    key: str
    value: str
    unit: str = ""
    source: str = ""
    note: str = ""


def load(path: Path) -> dict[str, Row]:
    rows: dict[str, Row] = {}
    with open(path, encoding="utf-8", newline="") as f:
        for i, r in enumerate(csv.DictReader(f), 2):
            key = (r.get("key") or "").strip()
            if not key or key.startswith("#"):
                continue
            if not KEY_RE.match(key):
                raise SystemExit(f"{path}:{i}: key '{key}' must be letters, digits and _ (start with a letter)")
            if key in rows:
                raise SystemExit(f"{path}:{i}: duplicate key '{key}'")
            rows[key] = Row(key, (r.get("value") or "").strip(), (r.get("unit") or "").strip(),
                            (r.get("source") or "").strip(), (r.get("note") or "").strip())
    return rows


def add(path: Path, key: str, value: str, unit: str = "", source: str = "", note: str = "") -> None:
    """Add or replace one row (keeps the order of the others)."""
    rows = load(path) if path.exists() else {}
    if not KEY_RE.match(key):
        raise SystemExit(f"bad key '{key}'")
    rows[key] = Row(key, str(value), unit, source, note)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(FIELDS)
        for r in rows.values():
            w.writerow([r.key, r.value, r.unit, r.source, r.note])


def macro_name(key: str) -> str:
    """LaTeX command names take letters only: digits become words, underscores split words (acc_v2 -> NumAccVtwo)."""
    digits = "zero one two three four five six seven eight nine".split()
    parts = re.split(r"_+", key)
    out = []
    for p in parts:
        p = re.sub(r"\d", lambda m: digits[int(m.group(0))], p)
        out.append(p[:1].upper() + p[1:])
    return "Num" + "".join(out)


def latex_escape(s: str) -> str:
    return s.replace("\\", r"\textbackslash{}").replace("%", r"\%").replace("&", r"\&").replace("#", r"\#").replace("_", r"\_")


def macros(rows: dict[str, Row]) -> str:
    out = ["% Generated by `python -m pa numbers macros` from 05_data/numbers.csv. Do not edit by hand.", ""]
    seen = {}
    for r in rows.values():
        name = macro_name(r.key)
        if name in seen:
            raise SystemExit(f"keys '{seen[name]}' and '{r.key}' give the same macro {name}")
        seen[name] = r.key
        unit = (r"\," + latex_escape(r.unit)) if r.unit and r.unit != "%" else latex_escape(r.unit)
        out.append(f"\\newcommand{{\\{name}}}{{{latex_escape(r.value)}{unit}\\xspace}}  % {r.key} <- {r.source}")
    return "\n".join(out) + "\n"


def fill(text: str, rows: dict[str, Row], with_unit: bool = True) -> tuple[str, list[str]]:
    missing = []

    def sub(m):
        k = m.group(1)
        if k not in rows:
            missing.append(k)
            return m.group(0)
        r = rows[k]
        if not with_unit or not r.unit:
            return r.value
        return r.value + ("%" if r.unit == "%" else " " + r.unit)
    return PLACE.sub(sub, text), missing


def _norm(v: str) -> str:
    return v.replace(",", "").replace(" ", "").rstrip("%")


def audit(text: str, rows: dict[str, Row]) -> dict:
    """Numbers typed in prose that no ledger value explains, and ledger keys that the text never uses."""
    used = set(PLACE.findall(text)) | {k for k in rows if "\\" + macro_name(k) in text}
    values = {_norm(r.value) for r in rows.values()}
    untraced = []
    for ln, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if s.startswith(("```", "<!--", "%")) or re.match(r"^\s*\[\d+\]", s):
            continue
        clean = PLACE.sub("", line)
        clean = re.sub(r"\\Num[A-Za-z]+", "", clean)
        clean = re.sub(r"\(\s*[A-Z][^()]*?\d{4}[a-z]?\s*\)", "", clean)     # (Author, 2024) citations
        clean = re.sub(r"\b(19|20)\d{2}[a-z]?\b", "", clean)                 # years
        clean = re.sub(r"https?://\S+|10\.\d{4,9}/\S+", "", clean)          # URLs and DOIs
        for m in NUM.finditer(clean):
            before = clean[max(0, m.start() - 12):m.start()]
            if SKIP_CONTEXT.search(before):
                continue
            if _norm(m.group(1)) not in values:
                untraced.append((ln, m.group(0).strip()))
    return {"untraced": untraced, "unused": [k for k in rows if k not in used], "used": sorted(used)}


def report(res: dict, name: str) -> str:
    out = [f"# numbers audit: {name}", "",
           "Typed numbers that no ledger value explains are candidates: move each into 05_data/numbers.csv with its "
           "source, or confirm it is not a result (a count of conditions, a setting stated in Methods).", "",
           f"## Numbers without a ledger entry — {len(res['untraced'])}", ""]
    out += [f"- L{ln}: `{v}`" for ln, v in res["untraced"][:300]]
    out += ["", f"## Ledger keys never used in the text — {len(res['unused'])}", ""]
    out += [f"- {k}" for k in res["unused"]]
    return "\n".join(out) + "\n"
